import { MOVE_MAPPER_GOLD_SET, GOLD_SET_CHECKED_AT } from "./move-mapper-gold-set";
import { MAPPER_DEFAULT_FPS } from "./move-mapper-spec";
import { TIMBA_SONG_ANATOMY_DATA } from "@/lib/constants/timba-song-anatomy";

/**
 * docs/ai-studio-move-mapper/song-maps.md: each song's sections as plain lines to paste into a
 * Move Mapper run ("Song map:"), so musicality rows use the player's section names. The times
 * belong to the song's own video; another upload of the same song is cut differently.
 */
export function buildSongMapsMarkdown(): string {
  const songs = TIMBA_SONG_ANATOMY_DATA.map((song) => {
    const lines = song.segments.map(
      (s) => `${s.formattedRange} ${s.sectionName} [${s.danceGear}]: ${s.musicalTrigger}`
    );
    return `## ${song.title} (\`${song.id}\`)

Only for https://www.youtube.com/watch?v=${song.youtubeVideoId}

\`\`\`
${lines.join("\n")}
\`\`\``;
  });

  return `# Song maps for the Move Mapper

Generated by \`npx tsx scripts/ai-studio-move-mapper.ts\` from the player's song data. Copy a song's block after "Song map:" in the app (or the chat message) when the clip is THAT video. The times fit only the video named under each song.

${songs.join("\n\n")}
`;
}

/** docs/ai-studio-move-mapper/gold-set.md, generated so the table always matches the data. */
export function buildGoldSetMarkdown(): string {
  const rows = MOVE_MAPPER_GOLD_SET.map((c, i) => {
    const expected = c.expected.length > 0 ? c.expected.map((id) => `\`${id}\``).join(" or ") : "**not-in-library**";
    const title = c.title.replace(/\|/g, "/");
    return `| ${i + 1} | ${c.figure} | ${expected} | [${title}](https://www.youtube.com/watch?v=${c.youtubeVideoId}) | ${c.channelTitle} |`;
  });

  return `# Move Mapper gold set

Generated by \`npx tsx scripts/ai-studio-move-mapper.ts\` from \`src/lib/moves/move-mapper-gold-set.ts\`. Edit the data, not this file.

These ${MOVE_MAPPER_GOLD_SET.length} clips have a known answer: each one teaches a figure named in its title. Run the Move Mapper on them before trusting it on professional dancers. Every video was found by web search and checked with YouTube oEmbed (public, embeddable) on ${GOLD_SET_CHECKED_AT}.

## How to run it

1. In the Move Mapper app (or an AI Studio chat set up as in the README), analyse each video at ${MAPPER_DEFAULT_FPS} frames per second. Long tutorials: let the segmenter cut them first.
2. Use the header the app asks for: clip id \`gold-<video id>\`, the title and channel from this table, dancers "unknown", no song id.
3. Save each answer as \`<video id>.json\` in one folder and run:

\`\`\`bash
npx tsx scripts/score-move-mapper.ts path/to/folder/*.json
\`\`\`

## What the score means

- **seen**: a high or medium row named the right move from what it saw. This is the goal.
- **heard**: right, but the row starts with "Name heard:", so it may have named it by ear. Tutorials say the name, so this is common; it still counts as correct.
- **low-only**: only a low-confidence row named it. The Mapper was unsure.
- **miss**: no row named it.
- **honest / forced** (the two clips we do not have, Tornillo and Figura 85): honest means it said "not-in-library"; forced means it pushed a catalogue name onto them. Forced is the worst result, because that is how wrong names reach dancers.

Other confident names are listed for information: tutorials show entries and exits (guapea, dile que no, enchufla), so they are not errors by themselves.

## The clips

| # | Figure | Right answer | Video | Channel |
|---|---|---|---|---|
${rows.join("\n")}

These are also good candidates for the move pages' videos. A teacher still picks the clip and the start and end times at /instructor/moves.
`;
}
